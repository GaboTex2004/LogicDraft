-- Additive schema for Phase 3.3: shared project conversations, collaborator/AI messages, and shared UML proposals.
-- Does not alter diagramas.contenido or existing V1/V2 tables.

CREATE TABLE conversaciones_agente (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    proyecto_id bigint NOT NULL,
    titulo character varying(140) NOT NULL,
    estado character varying(20) NOT NULL DEFAULT 'ACTIVE',
    creado_por_id bigint NOT NULL,
    creado_por_nombre character varying(100) NOT NULL,
    fecha_creacion timestamp(6) without time zone NOT NULL,
    fecha_actualizacion timestamp(6) without time zone NOT NULL,
    CONSTRAINT conversaciones_agente_pkey PRIMARY KEY (id),
    CONSTRAINT fk_conv_agente_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos(id),
    CONSTRAINT fk_conv_agente_creado_por FOREIGN KEY (creado_por_id) REFERENCES usuarios(id),
    CONSTRAINT chk_conv_agente_estado CHECK (estado IN ('ACTIVE', 'ARCHIVED'))
);

CREATE INDEX idx_conv_agente_proyecto_estado_fecha
    ON conversaciones_agente (proyecto_id, estado, fecha_actualizacion DESC, id DESC);

CREATE TABLE mensajes_conversacion_agente (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    conversacion_id bigint NOT NULL,
    proyecto_id bigint NOT NULL,
    autor_tipo character varying(20) NOT NULL,
    autor_usuario_id bigint,
    autor_nombre character varying(100) NOT NULL,
    solicitado_por_id bigint,
    solicitado_por_nombre character varying(100),
    contenido text NOT NULL,
    estado character varying(20) NOT NULL DEFAULT 'SENT',
    client_message_id character varying(100),
    mensaje_origen_id bigint,
    fecha_creacion timestamp(6) without time zone NOT NULL,
    CONSTRAINT mensajes_conversacion_agente_pkey PRIMARY KEY (id),
    CONSTRAINT fk_msg_agente_conversacion FOREIGN KEY (conversacion_id) REFERENCES conversaciones_agente(id),
    CONSTRAINT fk_msg_agente_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos(id),
    CONSTRAINT fk_msg_agente_autor_usuario FOREIGN KEY (autor_usuario_id) REFERENCES usuarios(id),
    CONSTRAINT fk_msg_agente_solicitado_por FOREIGN KEY (solicitado_por_id) REFERENCES usuarios(id),
    CONSTRAINT fk_msg_agente_origen FOREIGN KEY (mensaje_origen_id) REFERENCES mensajes_conversacion_agente(id),
    CONSTRAINT uk_msg_agente_conv_client_id UNIQUE (conversacion_id, client_message_id),
    CONSTRAINT chk_msg_agente_autor_tipo CHECK (autor_tipo IN ('USER', 'AGENT', 'SYSTEM')),
    CONSTRAINT chk_msg_agente_estado CHECK (estado IN ('SENT', 'PROCESSING', 'FAILED'))
);

CREATE INDEX idx_msg_agente_conv_id
    ON mensajes_conversacion_agente (conversacion_id, id DESC);

CREATE INDEX idx_msg_agente_origen
    ON mensajes_conversacion_agente (conversacion_id, mensaje_origen_id);

CREATE TABLE propuestas_uml_agente (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    version_lock bigint NOT NULL DEFAULT 0,
    conversacion_id bigint NOT NULL,
    mensaje_id bigint NOT NULL,
    proyecto_id bigint NOT NULL,
    solicitado_por_id bigint NOT NULL,
    solicitado_por_nombre character varying(100) NOT NULL,
    estado character varying(20) NOT NULL DEFAULT 'PENDING',
    base_revision bigint,
    aplicada_revision bigint,
    operaciones_json jsonb NOT NULL,
    elementos_afectados_json jsonb NOT NULL,
    resumen character varying(500),
    decidido_por_id bigint,
    decidido_por_nombre character varying(100),
    fecha_decision timestamp(6) without time zone,
    resultado_aplicacion character varying(500),
    fecha_creacion timestamp(6) without time zone NOT NULL,
    CONSTRAINT propuestas_uml_agente_pkey PRIMARY KEY (id),
    CONSTRAINT uk_prop_agente_mensaje UNIQUE (mensaje_id),
    CONSTRAINT fk_prop_agente_conversacion FOREIGN KEY (conversacion_id) REFERENCES conversaciones_agente(id),
    CONSTRAINT fk_prop_agente_mensaje FOREIGN KEY (mensaje_id) REFERENCES mensajes_conversacion_agente(id),
    CONSTRAINT fk_prop_agente_proyecto FOREIGN KEY (proyecto_id) REFERENCES proyectos(id),
    CONSTRAINT fk_prop_agente_solicitado_por FOREIGN KEY (solicitado_por_id) REFERENCES usuarios(id),
    CONSTRAINT fk_prop_agente_decidido_por FOREIGN KEY (decidido_por_id) REFERENCES usuarios(id),
    CONSTRAINT chk_prop_agente_estado CHECK (estado IN ('PENDING', 'ACCEPTED', 'REJECTED', 'STALE', 'INVALID'))
);

CREATE INDEX idx_prop_agente_proyecto_estado
    ON propuestas_uml_agente (proyecto_id, estado);

CREATE INDEX idx_prop_agente_conv_id
    ON propuestas_uml_agente (conversacion_id, id);
