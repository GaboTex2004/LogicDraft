import re


_TECHNICAL_OPERATION = re.compile(
    r"\b(?:ADD_ENTITY|DELETE_ENTITY|RENAME_ENTITY|UPDATE_CLASSIFIER|"
    r"ADD_ATTRIBUTE|DELETE_ATTRIBUTE|RENAME_ATTRIBUTE|CHANGE_ATTRIBUTE_TYPE|"
    r"SET_ATTRIBUTE_PRIMARY_KEY|SET_ATTRIBUTE_NULLABLE|SET_ATTRIBUTE_VISIBILITY|SET_ATTRIBUTE_STATIC|"
    r"ADD_METHOD|UPDATE_METHOD|DELETE_METHOD|"
    r"ADD_METHOD_PARAMETER|UPDATE_METHOD_PARAMETER|DELETE_METHOD_PARAMETER|"
    r"ADD_ENUM_LITERAL|RENAME_ENUM_LITERAL|DELETE_ENUM_LITERAL|"
    r"ADD_RELATIONSHIP|DELETE_RELATIONSHIP|UPDATE_RELATIONSHIP|"
    r"CREATE_ASSOCIATION|DELETE_ASSOCIATION|CONVERT_MANY_TO_MANY_ASSOCIATION)\b",
)


def contains_technical_operation(answer: str) -> bool:
    """Reject internal protocol identifiers instead of masking a bad model response."""
    return bool(_TECHNICAL_OPERATION.search(answer))
